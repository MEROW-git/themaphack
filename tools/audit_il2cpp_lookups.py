#!/usr/bin/env python3
"""Inventory literal IL2CPP interface references in project-owned native sources."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / "jni" / name for name in ("Main.cpp", "Render.h", "DrawMenu.h")]
SOURCES += sorted((ROOT / "jni" / "Config").rglob("*.h"))
SOURCES += sorted((ROOT / "jni" / "XYZ").rglob("*.h"))
SOURCES += sorted((ROOT / "jni" / "XYZ").rglob("*.cpp"))
PATTERN = re.compile(
    r'Il2Cpp(GetMethodOffset|GetFieldOffset|GetStaticFieldOffset|'
    r'GetStaticFieldValue|SetStaticFieldValue)\s*\(\s*'
    + r'\s*,\s*'.join([r'"([^"\n]*)"'] * 4)
    + r'(?:\s*,\s*(\d+))?', re.MULTILINE
)


def main():
    found = {}
    for path in SOURCES:
        if not path.is_file():
            continue
        source = path.read_text(encoding="utf-8", errors="replace")
        for match in PATTERN.finditer(source):
            kind, assembly, namespace, klass, member, argc = match.groups()
            key = (assembly, namespace, klass, member, kind, argc or "?")
            location = f"{path.relative_to(ROOT).as_posix()}:{source.count(chr(10), 0, match.start()) + 1}"
            found.setdefault(key, []).append(location)

    output = ROOT / "UNVERIFIED_GAME_INTERFACES.md"
    lines = [
        "# IL2CPP interface inventory",
        "",
        "Status: **UNVERIFIED** for MLBB 2.2.16.12322 / original-server patch 2.2.16a.",
        "",
        "Generated by `python tools/audit_il2cpp_lookups.py`. These are literal source references,",
        "including declarations and dormant or commented code. The inventory does not prove",
        "that an interface executes, exists in the target binary, or has the assumed ABI.",
        "`?` means the source does not supply an explicit argument count.",
        "",
        f"Total unique references: **{len(found)}**.",
        "",
        "| Assembly | Namespace / class | Member | Lookup | Args | Source |",
        "|---|---|---|---|---:|---|",
    ]
    for (assembly, namespace, klass, member, kind, argc), locations in sorted(found.items()):
        name = f"{namespace}.{klass}" if namespace else klass
        lines.append(
            f"| {assembly} | {name} | {member} | {kind} | {argc} | "
            + ", ".join(f"`{loc}`" for loc in locations) + " |"
        )
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(found)} unique lookups -> {output}")


if __name__ == "__main__":
    main()
